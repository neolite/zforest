//! "/structure" — how this demo is put together: the file tree the
//! generator scans and the pipeline from file → route → session.
const std = @import("std");
const zmeta = @import("../zmeta.zig");
const h = zmeta.h;

pub const params = struct {};

const tree =
    \\src/apps/zmeta_demo/
    \\  app.zig            manifest: Deps model + actions decl + Session = zmeta.Session(DemoDeps)
    \\  actions.zig        pub const actions = .{ "ping", "like" };  ← manifest input
    \\  pages/
    \\    index.zig        "/"        → Route.index,   params = struct {}
    \\    item/[id].zig    "/item/:id" → Route.item,    params = struct { id: u64 }
    \\                       pub fn prepare → 404 on unknown id
    \\    search.zig       "/search"   → Route.search,   env.query → zmeta.queryParam
    \\  gen/                GENERATED by `zig build gen` — checked in:
    \\    routes.zig        Route union, parseRoute, validPath, href, prepare, viewNodes
    \\    actions.zig       act.* comptime names + dispatch → D.on_<name>
    \\
    \\pipeline:
    \\  file tree ──gen.zig──► gen/*.zig ──compile──► Session(Deps) ──► server/http.zig
    \\     pages/                checked in        contract             transport
;

const flow =
    \\GET /item/7
    \\  → parseRoute("/item/7")        generated: segments → typed params { id: 7 }
    \\GET /search?q=zig                query lands on the session (Env.query),
    \\                               readable by prepare/view on every render
    \\  → setRoute / validPath        generated dispatch, bogus paths never mint a session
    \\  → page.prepare(params, env)   app hook: unknown id → error.NotFound → 404
    \\  → layouts∘view(a, params, env) page fn returns forest.Node tree
    \\  → writeView → SSR HTML        same tree also drives snapshot + diff
    \\  → EventSource /events?r=/item/7
    \\  → POST /action {"action":"like","arg":"7"}
    \\  → gen/actions dispatch → DemoDeps.on_like → bumpSeq
    \\  → after-flush: forest.diff → PatchLog → SSE patch {rev, ops}
;

pub fn view(a: std.mem.Allocator, s: anytype, p: params, env: *const zmeta.Env) h.Node {
    _ = s;
    _ = p;
    _ = env;
    return h.fragment(a, .{
        h.h1(a).id("title").child("how it's made").node(),
        h.p(a).id("blurb").child("one file per route — the generator does the rest").node(),
        h.h2(a).child("file structure").node(),
        h.pre(a).id("tree").class("code").child(tree).node(),
        h.h2(a).child("request lifecycle").node(),
        h.pre(a).id("flow").class("code").child(flow).node(),
        h.p(a).id("back").child(h.a(a).href("/").child("← back")).node(),
    });
}
